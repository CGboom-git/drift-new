"""Continue one trusted RCVR UNKNOWN checkpoint in three isolated online arms.

Each invocation restores the same pre-recovery state in a fresh Python process.
The original benchmark prefix is never regenerated by the model.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from agentdojo.functions_runtime import FunctionsRuntime
from agentdojo.task_suite.load_suites import get_suite
from agentdojo.task_suite.task_suite import functions_stack_trace_from_messages

from client import OpenAIModel
from DRIFTLLM import DRIFTLLM
from DRIFTTaskSuite import DRIFTTaskSuite
from rcdc.binding_witness import evaluate
from rcdc.checkpoint import load
from rcdc.integration import components
from rcdc.schema import canonical, digest
from utils import get_logger


MODES = {"reject": "strict", "allow": "allow", "recovery": "full"}


def resume(checkpoint_path, branch, output_dir):
    if branch not in MODES:
        raise ValueError("unknown_checkpoint_branch")
    state = load(checkpoint_path)
    context = state["context"]
    spec, call = state["spec"], state["call"]
    if context["suite"] != "banking" or context["task_id"] != "user_task_4":
        raise ValueError("pilot_restricted_to_banking_task4")
    if evaluate(spec, call, state["ledger"], context["relation_mode"]).json() != state["decision"].json():
        raise ValueError("checkpoint_initial_verdict_not_reproducible")

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    result_path = output_dir / f"{Path(checkpoint_path).stem}_{branch}.json"
    if result_path.exists():
        raise FileExistsError(f"branch_result_already_exists:{result_path}")
    logger = get_logger(str(output_dir / f"{branch}.log"))
    llm_state = copy.deepcopy(state["llm_state"])
    args = llm_state["args"]
    client = OpenAIModel(model=args.model, logger=logger, temperature=args.temperature,
                         max_retries=args.openai_max_retries)
    for key, value in state["client_counters"].items():
        if value is not None:
            setattr(client, key, copy.deepcopy(value))
    llm = DRIFTLLM(args, client, logger=logger)
    llm.__dict__.update(llm_state)
    llm.client, llm.logger = client, logger

    suite = get_suite(context["benchmark_version"], context["suite"])
    task = suite.get_user_task_by_id(context["task_id"])
    injection = (None if context["injection_task_id"] == "clean" else
                 suite.get_injection_task_by_id(context["injection_task_id"]))
    contracts_path = REPO / "contracts/agentdojo_ifc_global_tool_contract_semantic_review_gpt55.json"
    contracts = json.loads(contracts_path.read_text(encoding="utf-8"))
    events = []
    executor, loop = components(
        llm, context["task_id"], task.PROMPT, contracts,
        mode=MODES[branch], budget=context["recovery_budget"],
        relation_mode=context["relation_mode"], emit=events.append,
        enable_binding_verification=context["enable_binding_verification"],
        enable_evidence_isolation=context["enable_evidence_isolation"],
    )
    executor.spec = spec
    executor.ledger = copy.deepcopy(state["ledger"])
    # query() re-creates this same candidate. Its tick must match the frozen
    # position so the initial witness is evaluated at exactly the same time.
    executor.clock = state["clock"] - 1
    runtime = FunctionsRuntime(suite.tools)
    env = state["environment"].model_copy(deep=True)
    messages = copy.deepcopy(state["messages"])
    extra_args = copy.deepcopy(state["extra_args"])
    candidate = messages[-1]["tool_calls"][0]
    if candidate.id != call.call_id or candidate.function != call.tool or canonical(candidate.args) != call.arguments:
        raise ValueError("checkpoint_message_candidate_mismatch")
    initial_hash = digest(env.model_dump(mode="json"))
    if initial_hash != state["hashes"]["environment"]:
        raise ValueError("checkpoint_environment_hash_mismatch")

    _, _, final_env, final_messages, _ = loop.query(task.PROMPT, runtime, env, messages, extra_args)
    model_output = DRIFTTaskSuite.model_output_from_messages(None, final_messages) or ""
    stack = functions_stack_trace_from_messages(final_messages)
    pre_env = context["pre_environment"].model_copy(deep=True)
    utility = suite._check_task_result(task, model_output, pre_env, final_env, stack)
    security = (None if injection is None else
                suite._check_task_result(injection, model_output, pre_env, final_env, stack))
    result = {
        "checkpoint": str(checkpoint_path), "branch": branch,
        "initial_verdict": state["decision"].verdict,
        "candidate": {"tool": call.tool, "arguments": json.loads(call.arguments)},
        "spec_hash": spec.constraint_id, "environment_hash_pre": initial_hash,
        "environment_hash_post": digest(final_env.model_dump(mode="json")),
        "utility": utility, "security": security,
        "stopped": executor.stopped,
        "recovery_reads": sum(e.get("event") == "evidence_bounded_recovery_read_response" for e in events),
        "events": events,
        "messages": final_messages,
    }
    result_path.write_text(json.dumps(result, ensure_ascii=False, indent=2, default=str) + "\n",
                           encoding="utf-8")
    return result_path


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", type=Path, required=True)
    parser.add_argument("--branch", choices=tuple(MODES), required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    options = parser.parse_args()
    print(resume(options.checkpoint, options.branch, options.output_dir))
